CREATE DATABASE IF NOT EXISTS store_ratings;
USE store_ratings;
CREATE TABLE IF NOT EXISTS users (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(60) NOT NULL,
 email VARCHAR(255) NOT NULL UNIQUE, address VARCHAR(400) NOT NULL,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('ADMIN','USER','OWNER') NOT NULL DEFAULT 'USER',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CHECK(CHAR_LENGTH(name) BETWEEN 20 AND 60)
);
CREATE TABLE IF NOT EXISTS stores (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL,
 email VARCHAR(255) NOT NULL, address VARCHAR(400) NOT NULL,
 owner_user_id INT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(owner_user_id) REFERENCES users(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS ratings (
 id INT AUTO_INCREMENT PRIMARY KEY, store_id INT NOT NULL, user_id INT NOT NULL,
 rating TINYINT NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY uq_store_user(store_id,user_id), CHECK(rating BETWEEN 1 AND 5),
 FOREIGN KEY(store_id) REFERENCES stores(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
